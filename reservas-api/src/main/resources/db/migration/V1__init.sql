-- Necesaria para poder mezclar "=" (resource_id) y "&&" (rangos) en una restricción de exclusión
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL CHECK (role IN ('USER', 'ADMIN')),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE resources (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(500) NOT NULL DEFAULT '',
    capacity    INTEGER      NOT NULL CHECK (capacity > 0),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE reservations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id),
    resource_id BIGINT      NOT NULL REFERENCES resources (id),
    start_at    TIMESTAMPTZ NOT NULL,
    end_at      TIMESTAMPTZ NOT NULL,
    status      VARCHAR(20) NOT NULL CHECK (status IN ('CONFIRMED', 'CANCELLED')),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_reservations_dates CHECK (end_at > start_at),

    -- Garantía a nivel de base de datos contra el doble reservado: dos reservas CONFIRMADAS
    -- del mismo recurso no pueden tener rangos que se solapen. El rango es [inicio, fin), así
    -- que una reserva puede empezar justo cuando acaba otra. Las canceladas no cuentan.
    CONSTRAINT ex_reservations_no_overlap EXCLUDE USING gist (
        resource_id WITH =,
        tstzrange(start_at, end_at) WITH &&
    ) WHERE (status = 'CONFIRMED')
);

CREATE INDEX idx_reservations_user_start ON reservations (user_id, start_at DESC);
CREATE INDEX idx_reservations_resource_start ON reservations (resource_id, start_at);
CREATE INDEX idx_resources_active ON resources (active);
